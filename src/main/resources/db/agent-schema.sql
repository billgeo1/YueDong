CREATE TABLE IF NOT EXISTS `t_agent_session` (
  `id` bigint(20) NOT NULL AUTO_INCREMENT,
  `session_id` varchar(64) NOT NULL,
  `trace_id` varchar(64) NOT NULL,
  `mode` varchar(20) NOT NULL,
  `actor_type` varchar(20) NOT NULL,
  `actor_id` int(11) NOT NULL DEFAULT 0,
  `actor_name` varchar(80) DEFAULT NULL,
  `created_at` datetime NOT NULL,
  `last_active_at` datetime NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_agent_session_id` (`session_id`),
  KEY `idx_agent_session_actor` (`actor_type`, `actor_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `t_agent_tool_call` (
  `id` bigint(20) NOT NULL AUTO_INCREMENT,
  `trace_id` varchar(64) NOT NULL,
  `session_id` varchar(64) NOT NULL,
  `actor_type` varchar(20) NOT NULL,
  `actor_id` int(11) NOT NULL DEFAULT 0,
  `actor_name` varchar(80) DEFAULT NULL,
  `tool_name` varchar(80) NOT NULL,
  `tool_version` varchar(20) NOT NULL DEFAULT '1.0',
  `risk_level` varchar(20) NOT NULL,
  `request_summary` varchar(1000) DEFAULT NULL,
  `response_summary` varchar(1000) DEFAULT NULL,
  `status` varchar(30) NOT NULL,
  `latency_ms` bigint(20) NOT NULL DEFAULT 0,
  `confirmation_id` varchar(64) DEFAULT NULL,
  `idempotency_key` varchar(64) DEFAULT NULL,
  `created_at` datetime NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_agent_idempotency_key` (`idempotency_key`),
  KEY `idx_agent_tool_trace` (`trace_id`),
  KEY `idx_agent_tool_session` (`session_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `t_agent_confirmation` (
  `id` bigint(20) NOT NULL AUTO_INCREMENT,
  `token` varchar(64) NOT NULL,
  `trace_id` varchar(64) NOT NULL,
  `session_id` varchar(64) NOT NULL,
  `actor_type` varchar(20) NOT NULL,
  `actor_id` int(11) NOT NULL,
  `actor_name` varchar(80) DEFAULT NULL,
  `tool_name` varchar(80) NOT NULL,
  `risk_level` varchar(20) NOT NULL,
  `arguments_json` text NOT NULL,
  `title` varchar(200) NOT NULL,
  `impact` varchar(1000) NOT NULL,
  `status` varchar(30) NOT NULL,
  `idempotency_key` varchar(64) NOT NULL,
  `created_at` datetime NOT NULL,
  `expires_at` datetime NOT NULL,
  `executed_at` datetime DEFAULT NULL,
  `tool_call_id` bigint(20) DEFAULT NULL,
  `result_summary` varchar(1000) DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_agent_confirmation_token` (`token`),
  UNIQUE KEY `uk_agent_confirmation_idempotency` (`idempotency_key`),
  KEY `idx_agent_confirmation_session` (`session_id`),
  KEY `idx_agent_confirmation_status` (`status`, `expires_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
